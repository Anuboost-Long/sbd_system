#!/usr/bin/env python3
"""Build SBD.API/Services/Customers/Functions/PhoneLengthData.cs from libphonenumber's PhoneNumberMetadata.xml.

Usage: python3 scripts/generate_phone_table.py PhoneNumberMetadata.xml v9.0.44
Source: https://github.com/google/libphonenumber (Apache License 2.0).
For each country calling code, the allowed national-number lengths are the union of the
fixed-line and mobile lengths of every territory that uses the code (service and toll-free
numbers are left out, because customers give a contact number).
"""
import re
import sys
import xml.etree.ElementTree as ET


def parse_lengths(text):
    lengths = set()
    for part in text.split(","):
        part = part.strip()
        match = re.fullmatch(r"\[(\d+)-(\d+)\]", part)
        if match:
            lengths.update(range(int(match.group(1)), int(match.group(2)) + 1))
        elif part.isdigit():
            lengths.add(int(part))
    return lengths


def territory_lengths(territory):
    lengths = set()
    for kind in ("fixedLine", "mobile"):
        node = territory.find(kind)
        if node is not None:
            possible = node.find("possibleLengths")
            if possible is not None and "national" in possible.attrib:
                lengths |= parse_lengths(possible.attrib["national"])
    if not lengths:
        general = territory.find("generalDesc/possibleLengths")
        if general is not None and "national" in general.attrib:
            lengths = parse_lengths(general.attrib["national"])
    return lengths


def main(xml_path, version):
    by_code = {}
    for territory in ET.parse(xml_path).getroot().iter("territory"):
        code = territory.attrib.get("countryCode")
        if code:
            by_code.setdefault(code, set()).update(territory_lengths(territory))

    rows = "\n".join(
        f'        ["{code}"] = [{", ".join(str(n) for n in sorted(lengths))}],'
        for code, lengths in sorted(by_code.items(), key=lambda item: (len(item[0]), item[0]))
        if lengths
    )
    print(f'''// <auto-generated>
// Generated by scripts/generate_phone_table.py from libphonenumber PhoneNumberMetadata.xml ({version}).
// Source: https://github.com/google/libphonenumber, Apache License 2.0, Copyright (C) The Libphonenumber Authors.
// Only the allowed national-number lengths are used; the library itself is not a dependency.
// </auto-generated>
namespace SBD.API.Services.Customers.Functions;

public static class PhoneLengthData
{{
    public static readonly IReadOnlyDictionary<string, int[]> NationalLengths = new Dictionary<string, int[]>
    {{
{rows}
    }};
}}''')


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
